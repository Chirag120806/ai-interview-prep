const { GoogleGenAI } = require("@google/genai");
const puppeteer = require('puppeteer');
const { z } = require("zod");
const { zodToJsonSchema } = require("zod-to-json-schema");

const ai = new GoogleGenAI({
  apiKey: process.env.GOOGLE_GENAI_API_KEY,
});

const questionSchema = {
  type: "object",
  properties: {
    question: { type: "string" },
    intention: { type: "string" },
    answer: { type: "string" },
  },
  required: ["question", "intention", "answer"],
};

const interviewReportJsonSchema = {
  type: "object",
  properties: {
    title: {
      type: "string",
      description: "The title of the job for which the interview report is generated",
    },
    matchScore: { type: "number" },
    technicalQuestions: { type: "array", items: questionSchema },
    behavioralQuestions: { type: "array", items: questionSchema },
    skillGaps: {
      type: "array",
      items: {
        type: "object",
        properties: {
          skill: { type: "string" },
          severity: { type: "string", enum: ["low", "medium", "high"] },
        },
        required: ["skill", "severity"],
      },
    },
    preparationPlan: {
      type: "array",
      items: {
        type: "object",
        properties: {
          day: { type: "number" },
          focus: { type: "string" },
          tasks: { type: "array", items: { type: "string" } },
        },
        required: ["day", "focus", "tasks"],
      },
    },
  },
  required: [
    "title",
    "matchScore",
    "technicalQuestions",
    "behavioralQuestions",
    "skillGaps",
    "preparationPlan",
  ],
};

async function generateInterviewReport({ resume, selfDescription, jobDescription }) {
  const prompt = `
You are an expert technical interviewer.

Your task is to generate an interview preparation report
based on the candidate's resume, self-description and job description.

STRICT OUTPUT REQUIREMENTS:

1. Return ONLY valid JSON.
2. Follow the provided JSON schema exactly.
3. Do not add any additional properties.
4. Do not rename any property.
5. Do not return candidate_profile, interview_report,
   technical_assessment or any other alternative structure.

Generate the following:

- title: The job title taken from the job description.
- matchScore: A score between 0 and 100.
- technicalQuestions: At least 5 technical interview questions.
- behavioralQuestions: At least 5 behavioral interview questions.
- skillGaps: Identify missing or weak skills.
- preparationPlan: A complete 7-day preparation plan.

For every technical and behavioral question,
provide question, intention and answer.

Resume:
${resume}

Self Description:
${selfDescription}

Job Description:
${jobDescription}
`;

  const response = await ai.models.generateContent({
    model: "gemini-3-flash-preview",
    contents: prompt,
    config: {
      responseMimeType: "application/json",
      responseJsonSchema: interviewReportJsonSchema,
      maxOutputTokens: 16384,
    },
  });

  return JSON.parse(response.text);
}

async function generatePdfFromHtml(htmlContent) {
  const browser = await puppeteer.launch({
    executablePath: process.env.PUPPETEER_EXECUTABLE_PATH || undefined,
    headless: true,
    args: ["--no-sandbox", "--disable-setuid-sandbox"],
  });

  try {
    const page = await browser.newPage();
    await page.setContent(htmlContent, { waitUntil: "networkidle2" });
    return await page.pdf({
      format: "A4",
      printBackground: true,
      margin: { top: "20mm", bottom: "20mm", left: "15mm", right: "15mm" },
    });
  } finally {
    await browser.close();
  }
}

async function generateResumePdf ({ resume, selfDescription, jobDescription }) {
  const resumePdfSchema = z.object({
    html : z.string().describe("The HTML content of the resume which can be converted to PDF using any library like puppeteer")
  })

  const prompt = `Generate resume for a candidate with the following details :
  Resume : ${resume}
  Self Description : ${selfDescription}
  Job Description : ${jobDescription}
  
  the response should be a JSON object with a single field "html" which contains the HTML content of the resume which can be converted to PDF using any library like puppeteer.
  
  The resume should be tailored for the given job description and should highlight the candidate's strengths and relevant experience. The HTML content should be well-formatted and structured , making it easy to read.
  The content of resume should be not sound like it's generated by AI and should be as close as possible to a real human-written resume.
  You can highlight the content using some colors or different font styles but the overall design should be simple and professional.
  The content should be ATS friendly , i.e it should be easily parsable by ATS systems without losing important information.
  The resume should not be so lengthy, it should ideally be 1-2 pages long when converted to PDF. Focus on quality rather than quantity and make sure to include all the relevant information that can increase the candidate's chances of getting an interview call for the given job description.`

  const response = await ai.models.generateContent({
    model : "gemini-3-flash-preview",
    contents : prompt,
    config : {
      responseMimeType : "application/json",
      responseSchema : zodToJsonSchema(resumePdfSchema)
    }
  })

  const jsonContent =  JSON.parse(response.text);

  const pdfBuffer = await generatePdfFromHtml(jsonContent.html);

  return pdfBuffer;

}

module.exports = { generateInterviewReport, generateResumePdf };
